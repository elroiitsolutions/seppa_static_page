const deepMerge = (target: any, source: any): any => {
  if (!target) return source;
  if (!source) return target;
  const isObject = (obj: any) => obj && typeof obj === 'object' && !Array.isArray(obj);
  if (!isObject(target) || !isObject(source)) return target;
  
  const merged = { ...target };
  for (const key of Object.keys(source)) {
    if (isObject(source[key])) {
      merged[key] = deepMerge(target[key], source[key]);
    } else if (target[key] === undefined || target[key] === null) {
      merged[key] = source[key];
    }
  }
  return merged;
};

const loadNamespace = async (locale: string, name: string) => {
  const target = await import(`../messages/${locale}/${name}.json`).then(m => m.default).catch(() => ({}));
  if (locale === 'en') return target;
  const enFallback = await import(`../messages/en/${name}.json`).then(m => m.default).catch(() => ({}));
  return deepMerge(target, enFallback);
};

